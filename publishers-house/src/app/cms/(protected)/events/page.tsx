"use client";

import { useState, useEffect } from "react";
import { db } from "@/lib/firebase";
import { collection, getDocs, query, orderBy } from "firebase/firestore";
import Link from "next/link";
import ImageUpload from "../components/ImageUpload";

const S = {
  Navy: "#151A54", Blue700: "#0140C1", Blue500: "#2090FF",
  Paper100: "#F4F6FB", Paper200: "#E8ECF7", Paper300: "#D3DAEC",
  White: "#FFFFFF", Slate500: "#747CA1", Slate600: "#4A62A0",
  Red: "#DC2626", Green: "#16A34A",
  label: { fontFamily: "'Poppins', sans-serif", fontWeight: 600, fontSize: "11px", letterSpacing: "0.16em", textTransform: "uppercase" as const, display: "block", marginBottom: "6px", color: "#4A62A0" },
  input: { width: "100%", padding: "10px 12px", border: "1px solid #D3DAEC", borderRadius: "4px", fontFamily: "'Playfair Display', serif", fontSize: "15px", outline: "none", backgroundColor: "#FFFFFF" },
  btn: (bg: string, color: string) => ({ padding: "8px 16px", backgroundColor: bg, color, border: "none", borderRadius: "4px", cursor: "pointer", fontFamily: "'Poppins', sans-serif", fontWeight: 600, fontSize: "11px", letterSpacing: "0.14em", textTransform: "uppercase" as const }),
};

export interface EventDaySession {
  dayNumber: number;
  label: string;
  date?: string;
  title?: string;
  time?: string;
  speaker?: string;
  description?: string;
}

const emptyEvent = {
  title: "",
  summary: "",
  description: "",
  startAt: "",
  endAt: "",
  location: "",
  imageUrl: "",
  registrationUrl: "",
  speaker: "",
  scripture: "",
  published: false,
  days: [] as EventDaySession[],
};

export default function EventsEditor() {
  const [events, setEvents] = useState<any[]>([]);
  const [form, setForm] = useState({ ...emptyEvent });
  const [editingId, setEditingId] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [msg, setMsg] = useState("");

  const fetchEvents = async () => {
    try {
      const res = await fetch("/api/cms/events");
      if (res.ok) {
        const data = await res.json();
        if (data.events) {
          setEvents(data.events);
          return;
        }
      }
    } catch {}
    const q = query(collection(db, "events"), orderBy("startAt", "desc"));
    const snap = await getDocs(q);
    setEvents(snap.docs.map(d => ({ id: d.id, ...d.data() })));
  };

  useEffect(() => { fetchEvents(); }, []);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setLoading(true);
    try {
      const res = await fetch("/api/cms/events", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          action: "save",
          id: editingId,
          event: form,
        }),
      });
      const data = await res.json();
      if (!res.ok || data.error) {
        throw new Error(data.error || "Failed to save event");
      }
      setMsg(data.message || (editingId ? "Event updated ✓" : "Event added ✓"));
      setForm({ ...emptyEvent });
      setEditingId(null);
      fetchEvents();
    } catch (err: any) { setMsg("Error: " + err.message); }
    setLoading(false);
    setTimeout(() => setMsg(""), 3000);
  };

  const handleEdit = (ev: any) => {
    setForm({
      ...emptyEvent,
      ...ev,
      days: Array.isArray(ev.days) ? ev.days : [],
    });
    setEditingId(ev.id);
    window.scrollTo({ top: 0, behavior: "smooth" });
  };

  const handleDelete = async (id: string) => {
    if (!confirm("Delete this event?")) return;
    try {
      const res = await fetch("/api/cms/events", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ action: "delete", id }),
      });
      if (!res.ok) {
        const data = await res.json();
        throw new Error(data.error || "Failed to delete event");
      }
      fetchEvents();
    } catch (err: any) {
      alert("Error deleting event: " + err.message);
    }
  };

  const togglePublish = async (ev: any) => {
    try {
      const res = await fetch("/api/cms/events", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ action: "toggle_publish", id: ev.id, published: !ev.published }),
      });
      if (!res.ok) {
        const data = await res.json();
        throw new Error(data.error || "Failed to update event");
      }
      fetchEvents();
    } catch (err: any) {
      alert("Error updating event: " + err.message);
    }
  };

  const autoGenerateDays = () => {
    if (!form.startAt) {
      alert("Please specify a Start Date & Time first.");
      return;
    }
    const startDateStr = form.startAt.split("T")[0];
    const endDateStr = form.endAt ? form.endAt.split("T")[0] : startDateStr;
    const s = new Date(startDateStr + "T00:00:00").getTime();
    const e = new Date(endDateStr + "T00:00:00").getTime();
    const diff = Math.max(1, Math.round((e - s) / (1000 * 60 * 60 * 24)) + 1);

    const startObj = new Date(startDateStr + "T00:00:00");
    const sessions: EventDaySession[] = [];
    for (let i = 0; i < diff; i++) {
      const cur = new Date(startObj);
      cur.setDate(startObj.getDate() + i);
      const curDateStr = cur.toISOString().split("T")[0];
      const num = i + 1;
      sessions.push({
        dayNumber: num,
        label: `Day ${num}`,
        date: curDateStr,
        title: num === 1 ? "Opening Encounter" : num === diff && diff > 1 ? "Grand Finale & Impartation" : `Day ${num} Word & Power`,
        time: "4:00 PM WAT",
        speaker: form.speaker || "",
      });
    }
    setForm(prev => ({ ...prev, days: sessions }));
  };

  const addDay = () => {
    const nextNum = (form.days?.length || 0) + 1;
    setForm(prev => ({
      ...prev,
      days: [
        ...(prev.days || []),
        {
          dayNumber: nextNum,
          label: `Day ${nextNum}`,
          date: form.endAt?.split("T")[0] || form.startAt?.split("T")[0] || "",
          title: `Day ${nextNum} Session`,
          time: "4:00 PM WAT",
          speaker: form.speaker || "",
        },
      ],
    }));
  };

  const removeDay = (idx: number) => {
    setForm(prev => {
      const list = (prev.days || []).filter((_, i) => i !== idx);
      const renumbered = list.map((item, i) => ({
        ...item,
        dayNumber: i + 1,
        label: item.label.startsWith("Day ") ? `Day ${i + 1}` : item.label,
      }));
      return { ...prev, days: renumbered };
    });
  };

  const updateDay = (idx: number, field: keyof EventDaySession, val: any) => {
    setForm(prev => {
      const list = [...(prev.days || [])];
      list[idx] = { ...list[idx], [field]: val };
      return { ...prev, days: list };
    });
  };

  return (
    <div style={{ padding: "32px", maxWidth: "1100px", margin: "0 auto" }}>
      <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginBottom: "32px" }}>
        <div>
          <Link href="/cms" style={{ fontFamily: "'Poppins', sans-serif", fontSize: "12px", color: S.Blue500, textDecoration: "none" }}>← Dashboard</Link>
          <h1 style={{ fontFamily: "'Poppins', sans-serif", fontWeight: 700, fontSize: "28px", color: S.Navy, margin: "8px 0 0" }}>Events &amp; Multi-Day Conferences</h1>
        </div>
        <span style={{ fontFamily: "'Poppins', sans-serif", fontSize: "13px", color: S.Slate500 }}>{events.length} total · {events.filter(e => e.published).length} published</span>
      </div>

      {/* Form */}
      <div style={{ backgroundColor: S.White, border: `1px solid ${S.Paper300}`, borderRadius: "8px", padding: "28px", marginBottom: "40px" }}>
        <h2 style={{ fontFamily: "'Poppins', sans-serif", fontWeight: 600, fontSize: "18px", color: S.Navy, marginBottom: "24px" }}>
          {editingId ? "Edit Event" : "Add New Event"}
        </h2>
        <form onSubmit={handleSubmit}>
          <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: "16px" }}>
            {[
              ["title", "Event Title *", "text", true],
              ["location", "Location *", "text", true],
              ["startAt", "Start Date & Time *", "datetime-local", true],
              ["endAt", "End Date & Time (Multi-Day)", "datetime-local", false],
              ["registrationUrl", "Registration URL", "url", false],
              ["speaker", "Speaker / Minister", "text", false],
              ["scripture", "Scripture Reference (e.g. Isaiah 60:1)", "text", false],
              ["imageUrl", "Cover Image URL", "text", false],
            ].map(([field, label, type, required]) => (
              <div key={String(field)}>
                <label style={S.label}>{String(label)}</label>
                <input
                  type={String(type)}
                  placeholder={String(label)}
                  value={(form as any)[String(field)]}
                  onChange={e => setForm({ ...form, [String(field)]: e.target.value })}
                  required={!!required}
                  style={S.input}
                />
              </div>
            ))}
          </div>

          {/* Multi-Day Schedule Section (Day 1, Day 2, etc.) */}
          <div style={{ marginTop: "24px", border: `1px solid ${S.Paper300}`, borderRadius: "6px", padding: "18px", backgroundColor: "#F8FAFD" }}>
            <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginBottom: "12px", flexWrap: "wrap", gap: "10px" }}>
              <div>
                <label style={{ ...S.label, color: S.Blue700, marginBottom: 0 }}>Conference Day-by-Day Schedule</label>
                <span style={{ fontFamily: "'Poppins', sans-serif", fontSize: "12px", color: S.Slate500 }}>
                  ({form.days?.length || 0} Days configured)
                </span>
              </div>
              <div style={{ display: "flex", gap: "8px" }}>
                <button type="button" onClick={addDay} style={S.btn(S.Paper200, S.Navy)}>+ Add Day</button>
                <button type="button" onClick={autoGenerateDays} style={S.btn(S.Blue700, "#FFFFFF")}>⚡ Auto-Generate From Dates</button>
              </div>
            </div>

            {(!form.days || form.days.length === 0) ? (
              <p style={{ fontFamily: "'Poppins', sans-serif", fontSize: "12px", color: S.Slate500, margin: 0, fontStyle: "italic" }}>
                For multi-day conferences (Day 1, Day 2, etc.), set Start &amp; End dates above and click &ldquo;⚡ Auto-Generate From Dates&rdquo; or click &ldquo;+ Add Day&rdquo;.
              </p>
            ) : (
              <div style={{ display: "flex", flexDirection: "column", gap: "10px" }}>
                {form.days.map((dayItem, dIdx) => (
                  <div key={dIdx} style={{ backgroundColor: S.White, border: `1px solid ${S.Paper300}`, borderRadius: "6px", padding: "12px", display: "flex", flexDirection: "column", gap: "8px" }}>
                    <div style={{ display: "flex", gap: "8px", alignItems: "center" }}>
                      <input
                        type="text"
                        value={dayItem.label}
                        onChange={e => updateDay(dIdx, "label", e.target.value)}
                        placeholder={`Day ${dIdx + 1}`}
                        style={{ ...S.input, width: "90px", padding: "6px 8px", fontSize: "12px", fontWeight: 700, color: S.Blue700 }}
                      />
                      <input
                        type="date"
                        value={dayItem.date || ""}
                        onChange={e => updateDay(dIdx, "date", e.target.value)}
                        style={{ ...S.input, padding: "6px 8px", fontSize: "12px" }}
                      />
                      <input
                        type="text"
                        value={dayItem.time || ""}
                        onChange={e => updateDay(dIdx, "time", e.target.value)}
                        placeholder="Time (e.g. 4:00 PM WAT)"
                        style={{ flex: 1, ...S.input, padding: "6px 8px", fontSize: "12px" }}
                      />
                      <button type="button" onClick={() => removeDay(dIdx)} style={{ ...S.btn("#FEE2E2", S.Red), padding: "6px 10px" }}>✕</button>
                    </div>
                    <div style={{ display: "grid", gridTemplateColumns: "1.2fr 1fr", gap: "8px" }}>
                      <input
                        type="text"
                        value={dayItem.title || ""}
                        onChange={e => updateDay(dIdx, "title", e.target.value)}
                        placeholder="Session Theme / Title (e.g. Opening Night)"
                        style={{ ...S.input, padding: "6px 10px", fontSize: "12px" }}
                      />
                      <input
                        type="text"
                        value={dayItem.speaker || ""}
                        onChange={e => updateDay(dIdx, "speaker", e.target.value)}
                        placeholder="Minister(s) (e.g. Rev. Joshua Agunbiade)"
                        style={{ ...S.input, padding: "6px 10px", fontSize: "12px" }}
                      />
                    </div>
                  </div>
                ))}
              </div>
            )}
          </div>

          <div style={{ marginTop: "16px" }}>
            <label style={S.label}>Short Summary</label>
            <input type="text" placeholder="One-line description..." value={form.summary} onChange={e => setForm({ ...form, summary: e.target.value })} style={S.input} />
          </div>

          <div style={{ marginTop: "12px" }}>
            <label style={S.label}>Full Description</label>
            <textarea placeholder="Full event description..." value={form.description} onChange={e => setForm({ ...form, description: e.target.value })} rows={4} style={{ ...S.input, resize: "vertical" }} />
          </div>

          <div style={{ display: "flex", alignItems: "center", gap: "12px", marginTop: "16px" }}>
            <input type="checkbox" id="pub" checked={form.published} onChange={e => setForm({ ...form, published: e.target.checked })} />
            <label htmlFor="pub" style={{ fontFamily: "'Poppins', sans-serif", fontSize: "13px", color: S.Slate600 }}>Published (visible on website)</label>
          </div>

          {msg && <p style={{ color: msg.startsWith("Error") ? S.Red : S.Green, fontFamily: "'Poppins', sans-serif", fontSize: "13px", marginTop: "12px" }}>{msg}</p>}

          <div style={{ display: "flex", gap: "12px", marginTop: "20px" }}>
            <button type="submit" disabled={loading} style={S.btn(S.Blue700, "#fff")}>{loading ? "Saving..." : editingId ? "Update Event" : "Add Event"}</button>
            {editingId && <button type="button" onClick={() => { setForm({ ...emptyEvent }); setEditingId(null); }} style={S.btn(S.Paper200, S.Navy)}>Cancel</button>}
          </div>
        </form>
      </div>

      {/* List */}
      <div style={{ display: "flex", flexDirection: "column", gap: "12px" }}>
        {events.map(ev => {
          const dateRange = ev.endAt ? `${ev.startAt?.replace("T", " ")} → ${ev.endAt?.replace("T", " ")}` : ev.startAt?.replace("T", " ");
          const hasDays = Array.isArray(ev.days) && ev.days.length > 0;

          return (
            <div key={ev.id} style={{ display: "grid", gridTemplateColumns: "1fr auto", gap: "16px", alignItems: "center", backgroundColor: S.White, border: `1px solid ${S.Paper300}`, borderRadius: "6px", padding: "16px 20px" }}>
              <div>
                <div style={{ display: "flex", alignItems: "center", gap: "8px" }}>
                  <div style={{ fontFamily: "'Poppins', sans-serif", fontWeight: 600, fontSize: "15px", color: S.Navy }}>{ev.title}</div>
                  {hasDays && (
                    <span style={{ backgroundColor: "#FEF3C7", color: "#92400E", border: "1px solid #FDE68A", borderRadius: "4px", padding: "1px 6px", fontSize: "10px", fontWeight: 700, fontFamily: "'Poppins', sans-serif" }}>
                      {ev.days.length} Days Conference
                    </span>
                  )}
                </div>
                <div style={{ fontFamily: "'Poppins', sans-serif", fontSize: "12px", color: S.Slate500, marginTop: "4px" }}>
                  {dateRange} · {ev.location}
                </div>
              </div>
              <div style={{ display: "flex", gap: "8px", alignItems: "center" }}>
                <span style={{ fontFamily: "'Poppins', sans-serif", fontSize: "11px", padding: "3px 8px", borderRadius: "12px", backgroundColor: ev.published ? "#DCFCE7" : S.Paper200, color: ev.published ? S.Green : S.Slate500 }}>
                  {ev.published ? "Published" : "Draft"}
                </span>
                <button onClick={() => togglePublish(ev)} style={S.btn(S.Paper200, S.Navy)}>{ev.published ? "Unpublish" : "Publish"}</button>
                <button onClick={() => handleEdit(ev)} style={S.btn(S.Paper200, S.Navy)}>Edit</button>
                <button onClick={() => handleDelete(ev.id)} style={S.btn("#FEE2E2", S.Red)}>Delete</button>
              </div>
            </div>
          );
        })}
        {events.length === 0 && <p style={{ fontFamily: "'Playfair Display', serif", color: S.Slate500, textAlign: "center", padding: "40px" }}>No events yet. Add your first one above.</p>}
      </div>
    </div>
  );
}